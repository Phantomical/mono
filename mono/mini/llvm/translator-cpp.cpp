/* Missing overload for building an alloca with an alignment */
LLVMValueRef
mono_llvm_build_alloca (LLVMBuilderRef builder, LLVMTypeRef Ty, 
						LLVMValueRef ArraySize,
						int alignment, const char *Name)
{
	auto *b = unwrap (builder);
	Type *type = unwrap (Ty);
	/*
	 * Align(0) asserts in modern LLVM, and callers do pass 0 (e.g. the 'this'
	 * alloca) to mean "ABI default", so map 0 onto the preferred alignment.
	 */
	const DataLayout &dl = b->GetInsertBlock ()->getModule ()->getDataLayout ();
	Align align = alignment ? Align (alignment) : dl.getPrefTypeAlign (type);

	return wrap (b->Insert (new AllocaInst (type, 0, unwrap (ArraySize), align), Name));
}

LLVMValueRef
mono_llvm_build_load (LLVMBuilderRef builder, LLVMTypeRef Ty, LLVMValueRef PointerVal,
					  const char *Name, gboolean is_volatile)
{
	LoadInst *ins = unwrap(builder)->CreateLoad(unwrap (Ty), unwrap(PointerVal), is_volatile, Name);

	return wrap(ins);
}

LLVMValueRef
mono_llvm_build_atomic_load (LLVMBuilderRef builder, LLVMTypeRef Ty, LLVMValueRef PointerVal,
							 const char *Name, gboolean is_volatile, int alignment, BarrierKind barrier)
{
	LoadInst *ins = unwrap(builder)->CreateLoad(unwrap (Ty), unwrap(PointerVal), is_volatile, Name);

	/* alignment 0 means "ABI default", which the builder already applied. */
	if (alignment)
		ins->setAlignment (Align (alignment));
	switch (barrier) {
	case LLVM_BARRIER_NONE:
		break;
	case LLVM_BARRIER_ACQ:
		ins->setOrdering(Acquire);
		break;
	case LLVM_BARRIER_SEQ:
		ins->setOrdering(SequentiallyConsistent);
		break;
	default:
		g_assert_not_reached ();
		break;
	}

	return wrap(ins);
}

LLVMValueRef
mono_llvm_build_aligned_load (LLVMBuilderRef builder, LLVMTypeRef Ty, LLVMValueRef PointerVal,
							  const char *Name, gboolean is_volatile, int alignment)
{
	LoadInst *ins;

	ins = unwrap(builder)->CreateLoad(unwrap (Ty), unwrap(PointerVal), is_volatile, Name);
	/* alignment 0 means "ABI default", which the builder already applied. */
	if (alignment)
		ins->setAlignment (Align (alignment));

	return wrap(ins);
}

LLVMValueRef 
mono_llvm_build_store (LLVMBuilderRef builder, LLVMValueRef Val, LLVMValueRef PointerVal,
					  gboolean is_volatile, BarrierKind barrier)
{
	StoreInst *ins = unwrap(builder)->CreateStore(unwrap(Val), unwrap(PointerVal), is_volatile);

	switch (barrier) {
	case LLVM_BARRIER_NONE:
		break;
	case LLVM_BARRIER_REL:
		ins->setOrdering(Release);
		break;
	case LLVM_BARRIER_SEQ:
		ins->setOrdering(SequentiallyConsistent);
		break;
	default:
		g_assert_not_reached ();
		break;
	}

	return wrap(ins);
}

